#!/usr/bin/env python3
"""ghpush — push any folder to a new GitHub repo in one command.

Standard library only. Needs `git` and the GitHub CLI (`gh`).
"""
from __future__ import annotations

import argparse
import fnmatch
import os
import re
import shutil
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

# --------------------------------------------------------------------------
# Constants
# --------------------------------------------------------------------------

SKIP_DIRS = {".git", "node_modules", "venv", ".venv", "build", "dist", "target"}
MAX_FILE_BYTES = 100 * 1024 * 1024  # GitHub rejects files above 100 MB

MARKER_FILES = [
    ("package.json", "Node"),
    ("Cargo.toml", "Rust"),
    ("go.mod", "Go"),
    ("pom.xml", "Java"),
    ("build.gradle", "Java"),
    ("requirements.txt", "Python"),
    ("pyproject.toml", "Python"),
    ("setup.py", "Python"),
    ("CMakeLists.txt", "CMake"),
    ("composer.json", "Composer"),
]

EXTENSION_LANGS = {
    ".py": "Python",
    ".c": "C", ".h": "C",
    ".cpp": "C++", ".hpp": "C++", ".cc": "C++",
    ".java": "Java",
    ".js": "Node", ".ts": "Node",
    ".go": "Go",
    ".rs": "Rust",
}

SECRET_PATTERNS = [
    ".env", ".env.*", "*.pem", "*.key", "id_rsa*", "credentials.json", "*.p12",
]

SAFE_TEMPLATE_SUFFIXES = (".example", ".sample", ".template", ".dist")

LICENSES = {"mit", "gpl-3.0", "apache-2.0"}

SECRETS_BLOCK = """# Secrets
.env
*.pem
*.key
"""

FALLBACK_GITIGNORE = """# OS / editor
.DS_Store
Thumbs.db
.vscode/
.idea/
*.swp
""" + SECRETS_BLOCK + """# Build output
build/
dist/
*.o
*.out
"""

README_TEMPLATE = """# {name}

{description}

> ⚠️ This README was auto-generated by ghpush. Replace it with real documentation.

## About
TODO

## Tech stack
- {language}

## How to build / run
TODO

## License
TODO
"""

README_NAMES = {"readme.md", "readme", "readme.txt"}

# --------------------------------------------------------------------------
# Output helpers
# --------------------------------------------------------------------------

_COLOR = sys.stdout.isatty()


def _paint(code: str, text: str) -> str:
    return f"\033[{code}m{text}\033[0m" if _COLOR else text


def ok(msg: str) -> None:
    print(f"{_paint('32', '✔')} {msg}")


def warn(msg: str) -> None:
    print(f"{_paint('33', '⚠')} {msg}")


def fail(msg: str, code: int = 1) -> None:
    print(f"{_paint('31', '✖')} {msg}", file=sys.stderr)
    sys.exit(code)


def run(cmd: list[str], cwd=None, check: bool = True) -> subprocess.CompletedProcess:
    """Run a command, capturing text output."""
    return subprocess.run(cmd, cwd=cwd, check=check, capture_output=True, text=True)


# --------------------------------------------------------------------------
# Chunk 2 — pre-flight checks
# --------------------------------------------------------------------------

def check_tools() -> None:
    if not shutil.which("git"):
        fail("git is not installed. Install it with: sudo apt install git")
    if not shutil.which("gh"):
        fail("GitHub CLI (gh) is not installed. Install it with: sudo apt install gh\n"
             "  (or see https://github.com/cli/cli/blob/trunk/docs/install_linux.md)")


def check_gh_auth() -> None:
    if run(["gh", "auth", "status"], check=False).returncode != 0:
        fail("You are not logged in to GitHub. Run: gh auth login")


def check_git_identity() -> None:
    name = run(["git", "config", "user.name"], check=False).stdout.strip()
    email = run(["git", "config", "user.email"], check=False).stdout.strip()
    if not name or not email:
        fail("git identity is not set. Run:\n"
             '  git config --global user.name "Your Name"\n'
             '  git config --global user.email "you@example.com"')


# --------------------------------------------------------------------------
# Chunk 3 — folder path and user input
# --------------------------------------------------------------------------

def validate_folder(path: str) -> Path:
    folder = Path(path).expanduser().resolve()
    if not folder.exists():
        raise ValueError(f"Folder does not exist: {folder}")
    if not folder.is_dir():
        raise ValueError(f"Not a folder: {folder}")
    if folder == Path.home().resolve() or folder == Path(folder.anchor):
        raise ValueError(f"Refusing to push {folder} — pick a project folder instead")
    return folder


def sanitize_repo_name(name: str) -> str:
    cleaned = re.sub(r"\s+", "-", name.strip())
    cleaned = re.sub(r"[^A-Za-z0-9._-]", "", cleaned)[:100]
    if not cleaned or cleaned in {".", ".."}:
        raise ValueError(f"'{name}' is not a usable repository name")
    return cleaned


class Prompter:
    """Interactive input; with --yes every question just takes its default."""

    def __init__(self, assume_yes: bool = False):
        self.assume_yes = assume_yes

    def ask(self, prompt: str, default: str | None = None) -> str:
        if self.assume_yes and default is not None:
            return default
        suffix = f" [{default}]" if default is not None else ""
        try:
            answer = input(f"{prompt}{suffix}: ").strip()
        except EOFError:
            answer = ""
        return answer or (default or "")

    def confirm(self, prompt: str, default: bool = True) -> bool:
        if self.assume_yes:
            return default
        hint = "Y/n" if default else "y/N"
        try:
            answer = input(f"{prompt} [{hint}]: ").strip().lower()
        except EOFError:
            answer = ""
        return default if not answer else answer.startswith("y")


def ask_visibility(prompter: Prompter) -> str:
    while True:
        answer = prompter.ask("Visibility (public/private)", "public").lower()
        if answer in {"public", "private"}:
            return answer
        warn("Please type 'public' or 'private'.")


def github_login() -> str:
    return run(["gh", "api", "user", "--jq", ".login"], check=False).stdout.strip()


def repo_exists(owner: str, name: str) -> bool:
    return run(["gh", "repo", "view", f"{owner}/{name}"], check=False).returncode == 0


def ask_repo_name(prompter: Prompter, default_source: str, owner: str) -> str:
    try:
        default: str | None = sanitize_repo_name(default_source)
    except ValueError:
        default = None
    while True:
        raw = prompter.ask("Repository name", default)
        try:
            name = sanitize_repo_name(raw)
        except ValueError as exc:
            warn(str(exc))
            if prompter.assume_yes:
                fail("Cannot continue without a valid repository name.")
            continue
        if name != raw:
            ok(f"Name sanitized to: {name}")
        if owner and repo_exists(owner, name):
            warn(f"You already have a repository called '{name}'. Choose another name.")
            if prompter.assume_yes:
                fail("Repository name already taken.")
            default = None
            continue
        return name


# --------------------------------------------------------------------------
# Chunk 4 — language detection
# --------------------------------------------------------------------------

def walk_project(folder: Path):
    """os.walk that skips junk directories. Yields (dirpath, filenames)."""
    for dirpath, dirnames, filenames in os.walk(folder):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        yield Path(dirpath), filenames


def detect_language(folder: Path) -> str | None:
    for marker, template in MARKER_FILES:
        if (folder / marker).exists():
            return template
    counts: Counter[str] = Counter()
    for _, filenames in walk_project(folder):
        for fname in filenames:
            lang = EXTENSION_LANGS.get(Path(fname).suffix.lower())
            if lang:
                counts[lang] += 1
    return counts.most_common(1)[0][0] if counts else None


# --------------------------------------------------------------------------
# Chunk 5 — .gitignore
# --------------------------------------------------------------------------

def fetch_gitignore_template(language: str) -> str | None:
    templates = ["CMake", "C++"] if language == "CMake" else [language]
    parts = []
    for tpl in templates:
        result = run(["gh", "api", f"gitignore/templates/{tpl}", "--jq", ".source"],
                     check=False)
        if result.returncode != 0 or not result.stdout.strip():
            return None
        parts.append(result.stdout.rstrip() + "\n")
    return "\n".join(parts)


def ensure_gitignore(folder: Path, language: str | None, warnings: list[str]) -> str:
    """Create .gitignore if missing. Returns a description of what happened."""
    target = folder / ".gitignore"
    if target.exists():
        ok(".gitignore found, keeping it")
        return "existing"

    content = fetch_gitignore_template(language) if language else None
    if content is None:
        content = FALLBACK_GITIGNORE
        used = "built-in fallback"
        if language:
            warnings.append("Could not fetch a GitHub .gitignore template — used a minimal built-in one.")
        else:
            warnings.append("Language not detected — used a minimal built-in .gitignore.")
    else:
        used = f'GitHub "{language}" template'
        if ".env" not in content.splitlines():
            content = content.rstrip() + "\n\n" + SECRETS_BLOCK
    target.write_text(content, encoding="utf-8")
    ok(f".gitignore created ({used})")
    return used


# --------------------------------------------------------------------------
# Chunk 6 — README
# --------------------------------------------------------------------------

def has_readme(folder: Path) -> bool:
    return any(p.name.lower() in README_NAMES for p in folder.iterdir() if p.is_file())


def ensure_readme(folder: Path, name: str, description: str,
                  language: str | None, warnings: list[str]) -> bool:
    if has_readme(folder):
        return False
    (folder / "README.md").write_text(
        README_TEMPLATE.format(
            name=name,
            description=description or "TODO: add a description",
            language=language or "TODO",
        ),
        encoding="utf-8",
    )
    msg = "README.md was missing — a sample was created. Remember to write it later!"
    warn(msg)
    warnings.append(msg)
    return True


def ensure_license(folder: Path, key: str, warnings: list[str]) -> bool:
    """Write a LICENSE file from GitHub's license API. Returns True if written."""
    if any(p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING"))
           for p in folder.iterdir() if p.is_file()):
        ok("LICENSE found, keeping it")
        return False
    result = run(["gh", "api", f"licenses/{key}", "--jq", ".body"], check=False)
    if result.returncode != 0 or not result.stdout.strip():
        warnings.append(f"Could not fetch the '{key}' license — no LICENSE file was added.")
        warn(warnings[-1])
        return False
    holder = run(["git", "config", "user.name"], check=False).stdout.strip() or "Your Name"
    body = (result.stdout.replace("[year]", str(date.today().year))
            .replace("[fullname]", holder))
    (folder / "LICENSE").write_text(body.rstrip() + "\n", encoding="utf-8")
    ok(f"LICENSE created ({key})")
    return True


# --------------------------------------------------------------------------
# Chunk 7 — safety scan
# --------------------------------------------------------------------------

def is_safe_template(filename: str) -> bool:
    """True if a secret-looking filename is really a harmless template.

    Files like `.env.example` match the `.env.*` pattern but contain no real
    secrets, so people usually WANT them committed.
    """
    # endswith only looks at the LAST suffix, so ".env.example.local" stays flagged.
    return filename.lower().endswith(SAFE_TEMPLATE_SUFFIXES)


def is_secret(filename: str) -> bool:
    if is_safe_template(filename):
        return False
    return any(fnmatch.fnmatch(filename, pat) for pat in SECRET_PATTERNS)


def is_git_ignored(folder: Path, relpath: str) -> bool:
    return run(["git", "check-ignore", "-q", relpath], cwd=folder, check=False).returncode == 0


def scan_folder(folder: Path) -> tuple[list[str], list[str]]:
    """Return (secret files, files over 100 MB) as paths relative to folder."""
    secrets: list[str] = []
    big_files: list[str] = []
    for dirpath, filenames in walk_project(folder):
        for fname in filenames:
            full = dirpath / fname
            rel = str(full.relative_to(folder))
            if is_secret(fname):
                secrets.append(rel)
            try:
                if not full.is_symlink() and full.stat().st_size > MAX_FILE_BYTES:
                    big_files.append(rel)
            except OSError:
                pass
    return sorted(secrets), sorted(big_files)


def append_to_gitignore(folder: Path, entries: list[str]) -> None:
    target = folder / ".gitignore"
    existing = target.read_text(encoding="utf-8") if target.exists() else ""
    prefix = "" if not existing or existing.endswith("\n") else "\n"
    lines = "".join(f"/{e}\n" for e in entries)
    target.write_text(existing + prefix + "# Added by ghpush\n" + lines, encoding="utf-8")


def safety_scan(folder: Path, prompter: Prompter, warnings: list[str]) -> None:
    secrets, big_files = scan_folder(folder)
    secrets = [s for s in secrets if not is_git_ignored(folder, s)]
    big_files = [b for b in big_files if not is_git_ignored(folder, b)]

    if secrets:
        warn("Possible secrets found that are NOT ignored:")
        for s in secrets:
            print(f"    {s}")
        if prompter.confirm("Add them to .gitignore?", default=True):
            append_to_gitignore(folder, secrets)
            warnings.append(f"{len(secrets)} secret-looking file(s) added to .gitignore: {', '.join(secrets)}")
        else:
            warnings.append(f"Secret-looking files will be uploaded: {', '.join(secrets)}")

    if big_files:
        warn("Files over 100 MB (GitHub will reject the push):")
        for b in big_files:
            print(f"    {b}")
        if prompter.confirm("Add them to .gitignore? (No = abort)", default=True):
            append_to_gitignore(folder, big_files)
            warnings.append(f"{len(big_files)} large file(s) skipped: {', '.join(big_files)}")
        else:
            fail("Aborted: remove or ignore the large files and try again.")


# --------------------------------------------------------------------------
# Chunk 8 — git init and commit
# --------------------------------------------------------------------------

def git_init(folder: Path, prompter: Prompter) -> bool:
    """Make sure folder is a git repo. Returns True if it already was one."""
    if not (folder / ".git").exists():
        run(["git", "init", "-b", "main"], cwd=folder)
        return False
    remote = run(["git", "remote", "get-url", "origin"], cwd=folder, check=False)
    if remote.returncode == 0:
        warn(f"This repo already has an 'origin' remote: {remote.stdout.strip()}")
        if not prompter.confirm("Replace it?", default=False):
            fail("Aborted: existing remote kept.")
        run(["git", "remote", "remove", "origin"], cwd=folder)
    return True


def count_uploadable(folder: Path) -> int:
    out = run(["git", "ls-files", "--cached", "--others", "--exclude-standard"],
              cwd=folder).stdout
    return len([line for line in out.splitlines() if line])


def commit_all(folder: Path) -> bool:
    """Stage and commit everything. Returns True if a commit was made."""
    run(["git", "add", "-A"], cwd=folder)
    if not run(["git", "status", "--porcelain"], cwd=folder).stdout.strip():
        has_commits = run(["git", "rev-parse", "HEAD"], cwd=folder, check=False).returncode == 0
        if not has_commits:
            fail("Nothing to commit and the repo has no commits.")
        return False
    run(["git", "commit", "-m", "Initial commit (via ghpush)"], cwd=folder)
    return True


# --------------------------------------------------------------------------
# Chunk 9 — create the GitHub repo and push
# --------------------------------------------------------------------------

def build_create_command(name: str, visibility: str, description: str, folder: Path) -> list[str]:
    cmd = ["gh", "repo", "create", name, f"--{visibility}"]
    if description:
        cmd += ["--description", description]
    cmd += ["--source", str(folder), "--remote", "origin", "--push"]
    return cmd


def create_and_push(cmd: list[str]) -> None:
    result = run(cmd, check=False)
    if result.returncode == 0:
        return
    err = (result.stderr or result.stdout).strip()
    if "already exists" in err.lower():
        fail(f"A repository with that name already exists on GitHub.\n  {err}")
    fail(f"gh could not create/push the repository (safe to retry):\n  {err}")


def repo_url(owner: str, name: str) -> str:
    result = run(["gh", "repo", "view", f"{owner}/{name}", "--json", "url", "--jq", ".url"],
                 check=False)
    url = result.stdout.strip()
    return url if result.returncode == 0 and url else f"https://github.com/{owner}/{name}"


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------

def parse_args(argv=None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="ghpush",
        description="Push any folder to a new GitHub repo in one command.",
    )
    p.add_argument("folder", nargs="?", help="folder to push (asked for if omitted)")
    p.add_argument("--dry-run", action="store_true",
                   help="do everything except create the repo and push")
    p.add_argument("-y", "--yes", action="store_true",
                   help="skip confirmations and accept the defaults")
    p.add_argument("--license", choices=sorted(LICENSES), help="add a LICENSE file")
    p.add_argument("--org", help="create the repo under this organization")
    p.add_argument("--topics", help="comma-separated topics, e.g. c,graphics")
    p.add_argument("--web", action="store_true", help="open the repo in the browser at the end")
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    prompter = Prompter(args.yes)
    warnings: list[str] = []

    check_tools()
    check_gh_auth()
    check_git_identity()

    raw_folder = args.folder or prompter.ask("Folder to push")
    try:
        folder = validate_folder(raw_folder)
    except ValueError as exc:
        fail(str(exc))

    owner = args.org or github_login()
    name = ask_repo_name(prompter, folder.name, owner)
    description = prompter.ask("Description", "" if args.yes else None)
    visibility = ask_visibility(prompter)

    language = detect_language(folder)
    if language:
        ok(f"Detected language: {language}")
    else:
        warn("Could not detect language")

    ensure_gitignore(folder, language, warnings)
    ensure_readme(folder, name, description, language, warnings)
    if args.license:
        ensure_license(folder, args.license, warnings)

    git_init(folder, prompter)
    safety_scan(folder, prompter, warnings)

    n_files = count_uploadable(folder)
    if not prompter.confirm(f"About to upload {n_files} files to {visibility} repo {name}. Continue?"):
        fail("Aborted by user.")

    commit_all(folder)
    ok(f"Committed {count_uploadable(folder)} files")

    target = f"{args.org}/{name}" if args.org else name
    cmd = build_create_command(target, visibility, description, folder)
    if args.dry_run:
        print("\n[dry run] would run:\n  " + " ".join(repr(c) if " " in c else c for c in cmd))
        for w in warnings:
            warn(w)
        return 0

    create_and_push(cmd)
    url = repo_url(owner, name)
    ok(f"Created {url} and pushed")

    if args.topics:
        topics = [t.strip().lower() for t in args.topics.split(",") if t.strip()]
        edit = ["gh", "repo", "edit", f"{owner}/{name}"]
        for t in topics:
            edit += ["--add-topic", t]
        if topics and run(edit, check=False).returncode == 0:
            ok(f"Topics set: {', '.join(topics)}")
        elif topics:
            warnings.append("Could not set topics.")
    if args.web:
        run(["gh", "repo", "view", f"{owner}/{name}", "--web"], check=False)

    print(f"\n  Visibility: {visibility}\n  Language:   {language or 'unknown'}\n  Files:      {n_files}")
    for w in warnings:
        warn(w)
    return 0


if __name__ == "__main__":
    sys.exit(main())
